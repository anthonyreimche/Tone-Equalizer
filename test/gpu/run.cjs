// Runs the GPU spec (te.webgl.test.ts) through a SafeLight checkout's
// WebGL test harness — headless Chromium on SwiftShader, the real renderer,
// the real prepass framework — so the two stages are verified where the CPU
// suite cannot see: compilation with the host's namespacing, the inter-stage
// variable and the bag-driven draw counts on both process versions, the idle
// gate, the passes on half-float targets with bilinear taps at fractional
// spacings against the model (every filter, three presets and every
// luminance estimator), the mask probe and display, and an input mask whose
// square binary16 cannot hold.
//
// The spec is copied into the checkout for the run (its harness helpers and
// path aliases only resolve from inside) and removed again afterwards, along
// with the generated config. Point SAFELIGHT_CORE at the checkout; by default
// a `SafeLight` directory beside this repository or beside its parent folder
// is used. The browser server takes a port the OS hands out rather than
// vitest's fixed default, which Windows' dynamic port exclusions can swallow.
// SAFELIGHT_TEST_CHROME overrides the browser executable when Playwright's
// bundled Chromium will not start.
"use strict";

const fs = require("fs");
const net = require("net");
const path = require("path");
const { spawnSync } = require("child_process");

const extension = path.resolve(__dirname, "..", "..");
const isCheckout = (dir) => fs.existsSync(path.join(dir, "vitest.webgl.config.ts"));
const candidates = process.env.SAFELIGHT_CORE
  ? [path.resolve(process.env.SAFELIGHT_CORE)]
  : [path.join(extension, "..", "SafeLight"), path.join(extension, "..", "..", "SafeLight")];
const core = candidates.find(isCheckout);
if (!core) {
  console.error(`No SafeLight checkout found (tried ${candidates.join(", ")}); set SAFELIGHT_CORE`);
  process.exit(2);
}

const specDir = path.join(core, "src", "rendering", "webgl", "__te_gpu__");
const specFile = path.join(specDir, "te.webgl.test.ts");
const configFile = path.join(core, "vitest.te-gpu.config.ts");
const executablePath = process.env.SAFELIGHT_TEST_CHROME;

const config = (port) => `/// <reference types="vitest/config" />
// Generated by the Tone Equalizer extension's test/gpu/run.cjs —
// removed after the run. Same rig as vitest.webgl.config.ts, plus the
// extension's sources and its copied spec.
import path from "path";
import { readFileSync } from "fs";
import { defineConfig } from "vite";
import { playwright } from "@vitest/browser-playwright";

const pkg = JSON.parse(readFileSync(path.resolve(__dirname, "package.json"), "utf-8")) as { version: string };
const EXT = ${JSON.stringify(extension)};

export default defineConfig({
  cacheDir: "node_modules/.vite-cache-te-gpu",
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "src"),
      "libraw-wasm": path.resolve(__dirname, "src/raw/vendor/libraw-wasm/index.js"),
      "@te": path.join(EXT, "src"),
      "@te-test": path.join(EXT, "test"),
    },
  },
  server: { fs: { allow: [__dirname, EXT] } },
  optimizeDeps: { exclude: ["libraw-wasm"] },
  test: {
    name: "te-gpu",
    include: ["src/rendering/webgl/__te_gpu__/*.webgl.test.ts"],
    testTimeout: 600_000,
    browser: {
      enabled: true,
      headless: true,
      provider: playwright(),
      api: { port: ${port}, strictPort: true },
      instances: [
        {
          browser: "chromium",
          launch: {
            ${executablePath ? `executablePath: ${JSON.stringify(executablePath)},` : ""}
            args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"],
          },
        },
      ],
    },
  },
});
`;

function freePort() {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.unref();
    server.on("error", reject);
    server.listen(0, "127.0.0.1", () => {
      const { port } = server.address();
      server.close(() => resolve(port));
    });
  });
}

// Ctrl+C reaches the vitest child as well (same console or process group), so
// it exits and spawnSync returns. Without listeners Node would exit at once
// and skip the cleanup below, leaving the copies in the core checkout.
let interrupted = false;
for (const signal of ["SIGINT", "SIGTERM"]) {
  process.on(signal, () => {
    interrupted = true;
  });
}

async function main() {
  const port = await freePort();
  if (interrupted) process.exit(130);
  let status = 1;
  try {
    fs.mkdirSync(specDir, { recursive: true });
    fs.copyFileSync(path.join(__dirname, "te.webgl.test.ts"), specFile);
    fs.writeFileSync(configFile, config(port));
    const result = spawnSync("npx", ["vitest", "run", "--config", path.basename(configFile), "--reporter=verbose"], {
      cwd: core,
      stdio: "inherit",
      shell: true,
    });
    status = result.status ?? 1;
  } finally {
    fs.rmSync(specDir, { recursive: true, force: true });
    fs.rmSync(configFile, { force: true });
  }
  process.exit(status);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
